"""Collect the tagged review notes from lmsiq docstrings into one Markdown page.

Every docstring in ``src/`` may carry bullets whose text starts with one of the
tags ``Open question:``, ``Inconsistency:``, ``Bug:`` or ``Clean-up:``. This
script walks the source tree with :mod:`ast`, extracts those bullets together
with the object they belong to, and writes ``docs/open_questions.md`` grouped
by tag and by module. Run it (``make notes`` or ``python tools/collect_notes.py``
from ``docs/``) after editing docstrings; the page is committed so Read the Docs
does not need to run it.

A bullet is any line whose stripped text starts with ``- `` or ``* `` followed by
a tag, and continues over following lines that are indented deeper than the
bullet marker.
"""
from __future__ import annotations

import ast
import re
import sys
from collections import defaultdict
from pathlib import Path

TAGS = ('Open question', 'Inconsistency', 'Bug', 'Clean-up')
TAG_RE = re.compile(r'^[-*]\s+(' + '|'.join(re.escape(t) for t in TAGS) + r')s?:\s*(.*)$')

HERE = Path(__file__).resolve().parent
SRC = HERE.parent.parent / 'src'
OUT = HERE.parent / 'open_questions.md'


def iter_docstrings(tree: ast.Module, module: str):
    """Yield ``(qualified_name, docstring)`` for the module and every def/class."""
    doc = ast.get_docstring(tree, clean=True)
    if doc:
        yield module, doc
    stack = [(tree, module)]
    while stack:
        node, prefix = stack.pop()
        for child in ast.iter_child_nodes(node):
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                name = f'{prefix}.{child.name}'
                d = ast.get_docstring(child, clean=True)
                if d:
                    yield name, d
                stack.append((child, name))


def extract_bullets(doc: str):
    """Yield ``(tag, text)`` for each tagged bullet in a cleaned docstring."""
    lines = doc.splitlines()
    i = 0
    while i < len(lines):
        raw = lines[i]
        m = TAG_RE.match(raw.strip())
        if m:
            indent = len(raw) - len(raw.lstrip())
            text = [m.group(2).strip()]
            i += 1
            while i < len(lines):
                nxt = lines[i]
                if not nxt.strip():
                    break
                nxt_indent = len(nxt) - len(nxt.lstrip())
                if nxt_indent <= indent or TAG_RE.match(nxt.strip()):
                    break
                text.append(nxt.strip())
                i += 1
            yield m.group(1), ' '.join(text)
        else:
            i += 1


def collect():
    notes = defaultdict(lambda: defaultdict(list))   # tag -> module -> [(obj, text)]
    counts = defaultdict(int)
    for path in sorted(SRC.glob('*.py')):
        if path.name == '__init__.py':
            continue
        tree = ast.parse(path.read_text(encoding='utf-8'))
        module = path.stem
        for qualname, doc in iter_docstrings(tree, module):
            for tag, text in extract_bullets(doc):
                notes[tag][module].append((qualname, text))
                counts[tag] += 1
    return notes, counts


def render(notes, counts) -> str:
    out = ['# Open questions, inconsistencies, bugs and clean-up suggestions', '',
           'Generated by `docs/tools/collect_notes.py` from the tagged bullets in the',
           'docstrings under `src/`. Edit the docstrings, not this page. Each entry links',
           'to the API documentation of the object whose docstring carries it.', '',
           '| Tag | Count |', '|---|---|']
    for tag in TAGS:
        out.append(f'| {tag} | {counts.get(tag, 0)} |')
    out.append('')
    intro = {
        'Open question': 'Things the code does not settle and that need the author or a document to answer.',
        'Inconsistency': 'Places where two parts of the code, or the code and the instrument description, disagree.',
        'Bug': 'Behaviour that is wrong as written. Documented, not fixed.',
        'Clean-up': 'Suggestions for making the code importable, testable and reusable.',
    }
    for tag in TAGS:
        heading = {'Open question': 'Open questions', 'Inconsistency': 'Inconsistencies',
                   'Bug': 'Bugs', 'Clean-up': 'Clean-up suggestions'}[tag]
        out += [f'## {heading}', '', intro[tag], '']
        mods = notes.get(tag, {})
        if not mods:
            out += ['*None recorded.*', '']
            continue
        for module in sorted(mods):
            out += [f'### `{module}`', '']
            for qualname, text in mods[module]:
                role = 'mod' if qualname == module else ('class' if _is_class(qualname) else 'py:obj')
                out.append(f'- {{{role}}}`{qualname}`: {text}')
            out.append('')
    return '\n'.join(out) + '\n'


_CLASS_CACHE: dict[str, set[str]] = {}


def _is_class(qualname: str) -> bool:
    module = qualname.split('.')[0]
    if module not in _CLASS_CACHE:
        tree = ast.parse((SRC / f'{module}.py').read_text(encoding='utf-8'))
        _CLASS_CACHE[module] = {f'{module}.{n.name}' for n in ast.walk(tree) if isinstance(n, ast.ClassDef)}
    return qualname in _CLASS_CACHE[module]


def main() -> int:
    notes, counts = collect()
    OUT.write_text(render(notes, counts), encoding='utf-8', newline='\n')
    total = sum(counts.values())
    print(f'wrote {OUT} with {total} notes: ' + ', '.join(f'{t}={counts.get(t, 0)}' for t in TAGS))
    return 0


if __name__ == '__main__':
    sys.exit(main())
