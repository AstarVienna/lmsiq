#!/usr/bin/env python
"""
LMS-OPT-01 analysis: field of view, slice map and relative spectral response (lmsaiv program).

Implements the analysis of AIT performance test LMS-OPT-01 for the
``lmsaiv`` program (entry ``Opt01.fov``, registered as 'lms_opt_01_fov' in
``lmsaiv_opt_tests.OptTests``).  Flood-illuminated black-body flats are
coadded per LMS configuration, the slice edges are located from
along-column profiles, inter-slice gaps are measured, a slice map image is
painted, the illuminated field of view is estimated and a crude relative
response function (flood / black body) is displayed.

**Input data**: FITS mosaics in ``Filer.test_data_folder`` (e.g.
'../data/test_toysim', written by ``lmssim_toy`` using the file names
generated by ``lms_obs_map.ObsMap.get_configuration``):

- darks: files whose names contain all of ['lms_opt_01', '_dark'];
- flats: files containing ['lms_opt_01', 'flat_bb', 'stepN'] for N in
  2, 3 / 5, 6 / 8, 9 (nominal groups) and 11, 12, 13 (extended group).

Header keywords read: primary 'HIERARCH AIT OPTICON' ('nominal' /
'extended', written by ``lmssim_toy`` from the PolyFit configuration),
'HIERARCH ESO INS WLEN CEN' (micron; appears to come from the
'../config/sim_template.fits' template header), per-HDU 'ID' (detector
number as a string), 'X_CEN' (mm) and 'HIERARCH AIT PIXEL_PITCH'.  The
legacy ``flood_stats`` also reads 'HIERARCH ESO INS MODE'.

Design constants used: ``Globals.alpha_pix`` (8.7 mas per pixel),
``Globals.beta_slice`` (20.7 mas per slice), ``Globals.det_format``
(2048 x 2048).

**Output**:

- ``as_built['slice_map_' + opticon[0:3] + step_tag]`` (e.g.
  'slice_map_nomstep3', 'slice_map_nomstep9', 'slice_map_extstep13'): a
  ``Mosaic`` whose pixel value is the encoded slice number
  ``100 * pslice_no + fslice_no`` (0 = unilluminated).  This is the only
  product that persists (pickled by ``OptTests.run``).
- Printed: dark statistics, slice detection log, gap table (medium debug),
  field of view.
- Blocking matplotlib figures via ``lmsaiv_plot.Plot`` (slice map and
  relative response always; darks, floods, profiles and gaps at debug
  level 'low').

Notes
-----
- Bug: ``Opt02.dist`` reads ``as_built['slice_map_nominal']`` but this
  module stores 'slice_map_nom' + step tag (e.g. 'slice_map_nomstep3'), so
  the LMS-OPT-01 -> LMS-OPT-02 chain is broken as committed.
- Inconsistency: extended-mode field slices are taken as 11..13 in
  ``_find_slices`` (``slice_order``) while ``Globals.fslice_no_range``
  declares 12..14.
- Inconsistency: ``Globals.alpha_pix`` = 8.7 mas differs from the irdb
  METIS_LMS value of 8.2 mas; the FOV printed by ``_calculate_fov`` scales
  with it.
- Bug: ``_find_rrf`` multiplies 'HIERARCH AIT PIXEL_PITCH' by ``u.mm``
  although ``lmssim_toy`` writes ``Globals.nom_pix_pitch`` = 18.0
  (microns), making the pixel size 1000x too large and the wavelength ramp
  wrong.
- Inconsistency: ``flood_stats``, ``print_inter_slice`` and ``_parse_abo``
  are legacy routines written for the ``(name, hdr, hdus)`` tuple layout
  and are incompatible with ``lms_mosaic.Mosaic``; ``flood_stats`` is the
  only place the METIS-3667 check (> 0.500 arcsec2, aspect 1:1..2:1) is
  printed, and it is not called from ``fov``.
- Clean-up: results (gaps, FOV, RRF) are printed or plotted rather than
  returned; ``Plot`` calls end in ``plt.show()`` and block.

@author: Alistair Glasse
"""
import math
import astropy.units as u
import numpy as np
from astropy.convolution import Box1DKernel

from lmssim_model import Model
from lms_globals import Globals
from lmsaiv_opt_tools import OptTools
from lmsaiv_plot import Plot
from lms_filer import Filer
from lmsdist_util import Util

class Opt01:
    """LMS-OPT-01 field-of-view analysis (static methods).

    Public entry point is ``fov``; the private helpers implement the steps.
    ``flood_stats``, ``print_inter_slice`` and ``_parse_abo`` are legacy.

    Notes
    -----
    - ``__init__`` instantiates ``lmssim_model.Model`` for its side effects,
      but ``OptTests`` never instantiates ``Opt01``; ``Model`` is used only
      through its static ``black_body`` method.
    """

    def __init__(self):
        """Instantiate ``lmssim_model.Model`` (result discarded).

        Notes
        -----
        - Open question: the instantiation appears to be for initialisation side
          effects only; nothing in this module relies on it.
        """
        _ = Model()
        return

    @staticmethod
    def fov(title, as_built, **kwargs):
        """Run the LMS-OPT-01 analysis: field of view, slice map and relative response.

        Calls ``calculate_fov(as_built)`` and returns the updated 'as built'
        dictionary.  The dark-frame statistics that used to run first have
        moved to LMS-RAD-01 (``lmsaiv_rad01.Rad01.dark``).

        Parameters
        ----------
        title : str
            Analysis title from the ``OptTests`` registry.  Not used.
        as_built : dict
            'As built' dictionary loaded by ``lmsaiv.main``; extended in place
            with one slice-map entry per configuration group.
        **kwargs
            Accepted for interface compatibility; ignored (``lmsaiv.main``
            passes none; plotting is controlled by ``Globals.debug_level``).

        Returns
        -------
        dict
            ``as_built`` with the slice-map entries added.
        """
        as_built = Opt01.calculate_fov(as_built)
        print('Done')
        return as_built

    @staticmethod
    def calculate_fov(as_built):
        """Coadd the flood flats per configuration group and derive slice map, gaps, FOV and RRF.

        Upstream note: "This code is intended to be pasted directly into a
        notebook."

        For each optical configuration and step group in::

            {Globals.nominal:  [['2', '3'], ['9', '10'], ['12', '13']],
             Globals.extended: [['5', '6', '7']]}

        the first mosaic matching ['lms_opt_01', 'flat_bb', 'stepN'] is read for
        each step and coadded (``Mosaic.copy`` then ``Mosaic.add``) into a flood
        image named 'Coadded steps N,M'.  Then, in order: ``_find_slices(flood,
        smooth=3, snr_cut=10)``, ``_find_gaps``, ``_make_slice_map``, a slice-map
        plot, ``_calculate_fov`` and ``_find_rrf``.  The slice map is stored as
        ``as_built[slice_map.name]``, where ``_make_slice_map`` builds the name
        from the flood's primary header as
        'slice_map_<nom|ext>_eo<echelle order>_ea<p|n><1000 x |echelle angle|>'
        (e.g. 'slice_map_nom_eo27_eap01234').

        Parameters
        ----------
        as_built : dict
            Extended in place.

        Returns
        -------
        dict
            ``as_built``.

        Notes
        -----
        - Clean-up: ``slice_map_key`` ('slice_map_<nom|ext>_stepN') is computed
          but unused; the map's own name is the key.
        - Inconsistency: the coadded flood keeps the primary header of the
          first step in the group, so the slice-map name records that step's
          echelle order and angle only.
        - Bug: a missing flat file makes ``read_mosaic_list(...)[0]`` raise
          IndexError; every step of every group must be present.
        - Open question: step tags are matched as sub-strings ('step1' would also
          match 'step10'..'step19'); the steps used here avoid the collision.
        - Clean-up: the gap list from ``_find_gaps`` is only plotted, never
          stored; ``Plot.mosaic`` of the slice map is unconditional and blocks.
        """
        config_tag = {Globals.nominal: [['2', '3'], ['9', '10'], ['12', '13']],
                      Globals.extended: [['5', '6', '7']]}
        for opticon in config_tag:
            coadd_title = ''
            for step_list in config_tag[opticon]:
                flood = None
                for step in step_list:
                    step_tag = "step{:s}".format(step)
                    inc_filter = ['lms_opt_01', 'flat_bb', step_tag]
                    mosaic = Filer.read_mosaic_list(Filer.test_data_folder, inc_filter)[0]
                    # Coadd all flood images in each LMS configuration to support full coverage.
                    if Globals.is_debug('low'):
                        Plot.mosaic(mosaic)
                    if flood is None:
                        flood = mosaic.copy(clear_data=False, copy_name='')
                        coadd_title = 'Coadded steps ' + step + ','
                        continue
                    flood = flood.add(mosaic)
                    coadd_title += step + ','

                flood.name = coadd_title[0:-1]
                if Globals.is_debug('low'):
                    Plot.mosaic(flood)
                profiles = Opt01._find_slices(flood, smooth=3, snr_cut=10)
                slice_gaps = Opt01._find_gaps(profiles)
                if Globals.is_debug('low'):
                    Plot.slice_gaps(slice_gaps)
                slice_map = Opt01._make_slice_map(profiles, flood)
                Plot.mosaic(slice_map, title='Slice Map', cmap='hsv', mask=(0.0, 'black'))
                Opt01._calculate_fov(slice_map)
                Opt01._find_rrf(flood, slice_map)
                slice_map_key = 'slice_map_' + opticon[0:3] + '_' + step_tag
                as_built[slice_map.name] = slice_map
        return as_built

    @staticmethod
    def _find_gaps(profiles):
        """Compute the inter-slice gap for every pair of adjacent slices on the same detector and profile column.

        Parameters
        ----------
        profiles : dict of numpy.ndarray
            Slice-edge table from ``_find_slices`` with keys 'det_nos',
            'slice_nos', 'col_mins', 'col_maxs', 'row_mins', 'row_maxs' (one entry
            per detected slice per profile column).

        Returns
        -------
        list of tuple
            ``(det_no, slice_no_a, slice_no_b, col_min, col_max, gap)`` for every
            pair with the same detector, the same profile column band
            (``col_mins`` equal) and ``slice_no_b - slice_no_a == 1``; ``gap =
            row_mins[b] - row_maxs[a]`` in pixels (lower edge of the upper slice
            minus upper edge of the lower slice).  Consumed by ``Plot.slice_gaps``.

        Notes
        -----
        - The design value is ``Globals.intra_slice_gap`` = 20 pixels, but no
          comparison is made here.
        - In extended mode consecutive encoded slice numbers across a pupil-slice
          boundary (e.g. 113 -> 211) differ by more than 1, so no gap is reported
          between the SPIFU groups.
        - Clean-up: O(n^2) double loop; the table is printed only at debug level
          'medium'.
        """
        fmt = None
        gap_list = []
        if Globals.is_debug('medium'):
            fmt = "{:>10s},{:>10s},{:>10s},{:>10s},{:>10s},{:>14s}"
            print(fmt.format('det_no', 'slice_a', 'slice_b', 'col_min', 'col_max', 'gap'))
            fmt = "{:>10d},{:>10d},{:>10d},{:>10d},{:>10d},{:>14.3f}"

        n_profiles = profiles['det_nos'].shape[0]
        for i in range(0, n_profiles):
            for j in range(0, n_profiles):
                if i == j:
                    continue
                det_no_i = profiles['det_nos'][i]
                det_no_j = profiles['det_nos'][j]
                if det_no_j != det_no_i:
                    continue
                slice_no_i = profiles['slice_nos'][i]
                slice_no_j = profiles['slice_nos'][j]
                if slice_no_j - slice_no_i != 1:
                    continue
                col_min_i = profiles['col_mins'][i]
                col_min_j = profiles['col_mins'][j]
                if col_min_j != col_min_i:
                    continue
                col_max_j = profiles['col_maxs'][j]
                gap_size = profiles['row_mins'][j] - profiles['row_maxs'][i]
                if Globals.is_debug('medium'):
                    print(fmt.format(det_no_i, slice_no_i, slice_no_j, col_min_j, col_max_j, gap_size))
                gap = det_no_i, slice_no_i, slice_no_j, col_min_j, col_max_j, gap_size
                gap_list.append(gap)
        return gap_list

    @staticmethod
    def _find_rrf(flood, slice_map):
        """Divide the coadded flood by a 1000 K black body to display a relative response function.

        For each detector the illuminated pixels (``slice_map > 0``) of the flood
        image are divided by ``Model.black_body(waves, tbb=1000.)`` evaluated on
        an explicitly approximate linear wavelength ramp::

            disp  = 0.08 um / (2 * n_det_cols)          per column
            waves = WLEN_CEN + disp * (c_det_org + col)

        where ``c_det_org = X_CEN / PIXEL_PITCH - n_det_cols / 2`` is the mosaic
        column of the detector's first column.  The result is shown with
        ``Plot.mosaic`` and discarded.

        Parameters
        ----------
        flood : Mosaic
            Coadded flood image; primary keyword 'HIERARCH ESO INS WLEN CEN'
            (micron) and per-HDU 'X_CEN' (mm) and 'HIERARCH AIT PIXEL_PITCH' are
            read.
        slice_map : Mosaic
            Slice map from ``_make_slice_map``; copied as the output template, so
            unilluminated pixels keep the value 0 and are masked black in the
            plot.

        Returns
        -------
        None
            Plot only.

        Notes
        -----
        - Bug: 'HIERARCH AIT PIXEL_PITCH' is written by ``lmssim_toy`` as
          ``Globals.nom_pix_pitch`` = 18.0 (microns) but is multiplied by
          ``u.mm`` here, so ``c_det_cen`` is about 1.1 instead of about 1086
          columns and the wavelength ramp is offset.
        - Open question: the 0.08 um per detector-pair dispersion is a
          placeholder ('Very approximate dispersion...!'); the ``lmsdist``
          transforms or the irdb TRACE_LMS wavelength map would give the real
          lambda(x, y).
        - Clean-up: ``cols`` spans 0..4095 although each detector has 2048
          columns; the extra entries are unused.  Return the RRF mosaic instead of
          plotting it.
        """
        # Generate relative response tuple.
        cols = np.arange(0, 4096, 1)
        rrf = slice_map.copy(copy_name='rel_res_function')

        wave_mosaic_cen = flood.primary_hdr['HIERARCH ESO INS WLEN CEN'] * u.micron
        for i in range(0, 4):
            slice_map_data = slice_map.hdu_list[i].data
            slice_mask = np.where(slice_map_data > 0., 1., 0.)
            # Very approximate dispersion...!
            hdr = flood.hdu_list[i].header
            flood_image = flood.hdu_list[i].data
            x_det_cen = float(hdr['X_CEN']) * u.mm
            n_det_rows, n_det_cols = flood_image.shape
            pix_size = float(hdr['HIERARCH AIT PIXEL_PITCH']) * u.mm
            c_det_cen = x_det_cen / pix_size
            c_det_org = c_det_cen - n_det_cols / 2
            disp = .08 * u.micron / (2. * n_det_cols)
            waves = wave_mosaic_cen + disp * (c_det_org + cols)
            flux = Model.black_body(waves, tbb=1000.)
            rrf_image = rrf.hdu_list[i].data
            for row in range(0, n_det_rows):
                idx = np.argwhere(slice_mask[row] > 0.)
                rrf_image[row, idx] = flood_image[row, idx] / flux[idx]
            rrf.hdu_list[i].data = rrf_image
        Plot.mosaic(rrf, title='Rel Response Function', cmap='grey', mask=(0.0, 'black'))
        return

    @staticmethod
    def _find_slices(mosaic, smooth=None, snr_cut=5):
        """Locate slice edges from along-column profiles of a flood-illuminated mosaic.

        For each detector HDU and each profile column in [400, 800, 1200, 1600],
        the mean of the 9 columns ``[col - 4, col + 4]`` is taken along rows,
        optionally smoothed with ``astropy.convolution.Box1DKernel(smooth)``,
        and a noise level is estimated as the standard deviation of rows 0:70.
        Working upwards from row 0 the routine then repeatedly:

        1. finds the first row above ``snr_cut * noise``;
        2. takes the peak within the next ``slice_hw`` = 70 rows as the slice
           brightness and sets the cut level to 50 % of it;
        3. finds the lower and upper 50 %-crossings with linear interpolation
           between adjacent rows (``rlo``, ``rhi``);
        4. records the edges, then zeroes the profile up to ``rhi + gap_hw``
           (``gap_hw`` = 7) and advances the slice counter.

        Slice numbering follows ``slice_order``: in nominal mode detectors 1, 2
        carry field slices 15..28 and detectors 3, 4 slices 1..14 (pupil slice
        0); in extended mode field slices 11..13 repeat for pupil slices 1..3
        (detectors 1, 2) or 4..6 (detectors 3, 4), with ``spifu_gap`` = 200 rows
        blanked between pupil-slice groups.  Numbers are encoded with
        ``Util.encode_slice_no`` as ``100 * pslice_no + fslice_no``.

        Parameters
        ----------
        mosaic : Mosaic
            Flood image; primary keyword 'HIERARCH AIT OPTICON' selects the slice
            order, per-HDU 'ID' gives the detector number.
        smooth : int or None, optional
            Boxcar width in rows; None (default) disables smoothing.
        snr_cut : float, optional
            Detection threshold in units of the row 0:70 noise.  Default 5.

        Returns
        -------
        dict of numpy.ndarray
            Keys 'det_nos', 'slice_nos', 'col_mins' (col - 4), 'col_maxs'
            (col + 5, exclusive), 'row_mins' (lower edge ``rlo``), 'row_maxs'
            (upper edge ``rhi``), one entry per slice per profile column.

        Notes
        -----
        - The profile tuples ``(label, colour, det_no, profile_column,
          raw_signal, pts)`` are built for ``Plot.profiles`` (shown at debug
          'low') but are not returned.
        - Inconsistency: extended-mode field slices 11..13 here versus
          ``Globals.fslice_no_range[extended]`` = 12..14.
        - Inconsistency: local ``gap`` = 15 (``gap_hw`` = 7) versus
          ``Globals.intra_slice_gap`` = 20.
        - Bug: when no row exceeds the threshold the IndexError is caught and a
          message printed, but the loop continues with the stale ``row_lo`` and
          ``more_rows`` still True, so the following ``argwhere(...)[0][0]`` can
          raise an uncaught IndexError.
        - Open question: the loop ends only after the expected number of slices
          has been counted; a missed slice shifts the numbering of all slices
          above it on that column.
        - Open question: the noise estimate assumes rows 0:70 are unilluminated
          on every detector.
        - Clean-up: the previous docstring read 'Calculate fov and return
          dictionary of slice_bounds'; the FOV is computed in ``_calculate_fov``.
        """
        opticon = mosaic.primary_hdr['HIERARCH AIT OPTICON']
        slice_order = {Globals.nominal: {'12': (0, 0, 15, 28), '34': (0, 0, 1, 14)},
                       Globals.extended: {'12': (1, 3, 11, 13), '34': (4, 6, 11, 13)}
                       }
        cut = 0.5       # Fraction of bright signal defining cut level
        print()
        print("File = {:s}".format(mosaic.name))
        print("Identifying slices from along column profiles of flood illuminated images ")
        fmt = "Design fov, alpha pixel x slice width = {} x {}"
        print(fmt.format(Globals.alpha_pix, Globals.beta_slice))

        # Approximate slice image dimensions
        slice_width = 140
        slice_hw = int(0.5 * slice_width)
        gap = 15
        gap_hw = int(0.5 * gap)
        spifu_gap = 200

        slice_coords = {'det_nos': [], 'slice_nos': [],
                        'col_mins': [], 'col_maxs': [],
                        'row_mins': [], 'row_maxs': []}

        profile_colours = ['red', 'blue', 'green', 'magenta']
        pc_list_default = [400, 800, 1200, 1600]
        profile_column_list = {1: pc_list_default,
                               2: pc_list_default,
                               3: pc_list_default,
                               4: pc_list_default}
        profiles = []
        for hdu in mosaic.hdu_list:
            det_no = int(hdu.header['ID'])
            det_tag = {1: '12', 2: '12', 3: '34', 4: '34'}[det_no]
            det_slice_order = slice_order[opticon]
            pslice_start, pslice_end, fslice_start, fslice_end = det_slice_order[det_tag]

            img = hdu.data
            profile_columns = profile_column_list[det_no]
            for i, profile_column in enumerate(profile_columns):
                pslice_no = pslice_start
                fslice_no = fslice_start
                pc1, pc2 = profile_column - 4, profile_column + 5
                if Globals.is_debug('high'):
                    print('Opt01._find_slices, '
                          'det_no= ', det_no, 'pslice_no= ', pslice_no, 'fslice_no= ',
                          fslice_no, 'col= ', profile_column)
                raw_signal = np.mean(img[:, pc1:pc2], axis=1)
                signal = np.copy(raw_signal)
                if smooth is not None:
                    boxcar = Box1DKernel(smooth)
                    signal = np.convolve(signal, boxcar, mode='same')
                bgd_noise_level = np.std(signal[0:70])
                row_lo = 0
                pts = []
                more_rows = True
                while more_rows:
                    try:
                        row_lo += np.argwhere(signal[row_lo:] > snr_cut * bgd_noise_level)[0][0]
                    except IndexError:
                        fmt = 'Profile detection failed at det_no= {:d}, col= {:d}, row= {:d}'
                        print(fmt.format(det_no, profile_column, row_lo))
                    row_bright = row_lo + np.argmax(signal[row_lo:row_lo + slice_hw])
                    y_bright = signal[row_bright]                 # Typical peak signal in slice
                    y_cut = cut * y_bright
                    # Advance to row above cut signal level
                    row_lo += np.argwhere(signal[row_lo:] > cut * y_bright)[0][0]      # Row after 50 % point
                    y_a, y_b = signal[row_lo-1], signal[row_lo]
                    dr = (y_cut - y_a) / (y_b - y_a)
                    rlo = row_lo + dr - 1                           # Add pixel fraction for cut level.

                    row_hi = row_bright + np.argwhere(signal[row_bright:] < y_cut)[0][0]
                    y_a, y_b = signal[row_hi - 1], signal[row_hi]
                    dr = (y_cut - y_a) / (y_b - y_a)
                    rhi = row_hi + dr - 1
                    if Globals.is_debug('high'):
                        print("- {:5.2f}, {:5d}, {:5.2f}, {:5.3f}".format(rlo, row_bright, rhi, y_cut))
                    slice_coords['det_nos'].append(det_no)
                    slice_no = Util.encode_slice_no(fslice_no, pslice_no)
                    slice_coords['slice_nos'].append(slice_no)
                    slice_coords['col_mins'].append(pc1)
                    slice_coords['col_maxs'].append(pc2)
                    slice_coords['row_mins'].append(rlo)
                    slice_coords['row_maxs'].append(rhi)

                    pts.append((rlo, y_cut))
                    pts.append((rhi, y_cut))

                    # Remove slice from profile data
                    # signal[row_lo - gap_hw: row_hi + gap_hw] = 0.
                    signal[0: row_hi + gap_hw] = 0.

                    fslice_no += 1
                    if fslice_no > fslice_end:        # this should only be true in extended mode.
                        signal[row_lo - gap_hw: row_hi + spifu_gap] = 0.
                        fslice_no = fslice_start
                        pslice_no += 1
                        if pslice_no > pslice_end:
                            more_rows = False
                label = "col={}".format(profile_column)
                colour = profile_colours[i]
                profile = label, colour, det_no, profile_column, raw_signal, pts
                profiles.append(profile)

        # Convert lists to numpy arrays
        for key in slice_coords:
            slice_coords[key] = np.array(slice_coords[key])
        if Globals.is_debug('low'):
            Plot.profiles(profiles)
        return slice_coords

    @staticmethod
    def _make_slice_map(slice_coords, mosaic):
        """Paint a slice-number map from the measured slice edges.

        For every detector and every slice number seen on it, the lower and upper
        edges from ``slice_coords`` are fitted as quadratics in the profile-band
        centre column (``np.polyfit(cols, rows, 2)``) and evaluated at all 2048
        columns; the pixels between the rounded lower edge (inclusive) and upper
        edge (exclusive) are set to the encoded slice number
        ``N = 100 * pslice_no + fslice_no``.  Unilluminated pixels stay 0.

        Parameters
        ----------
        slice_coords : dict of numpy.ndarray
            Edge table from ``_find_slices``.
        mosaic : Mosaic
            Template whose geometry and headers are copied
            (``copy(clear_data=True, copy_name='slice_map')``).

        Returns
        -------
        Mosaic
            Slice map, stored in ``as_built`` by ``_find_fov`` and read by
            ``Opt02.dist`` / ``Opt02._extract_det_traces`` (slice strip
            extraction) as well as ``_find_rrf`` and ``_calculate_fov``.

        Notes
        -----
        - Bug: ``idxs = np.argwhere(slice_coords['slice_nos'] == slice_no)`` is
          not restricted to the current detector, so in nominal mode (where
          detectors 1 and 2, and 3 and 4, carry the same slice numbers) the edge
          fit for one detector mixes in the measurements of its partner.
        - Clean-up: ``row_mins`` is indexed with shape (n, 1) while the other
          arrays use ``[:, 0]``; ``np.polyfit`` / ``np.polyval`` happen to
          broadcast correctly.
        - The quadratic requires at least three profile columns; four are used.
        """
        opticon = mosaic.primary_hdr['HIERARCH AIT OPTICON']
        ech_order = mosaic.primary_hdr['HIERARCH ACHG REF_ECH_ORD']
        ech_ang = mosaic.primary_hdr['HIERARCH AIT ECH_ANG']
        ea_sign = 'n' if ech_ang < 0. else 'p'
        ea_tag = "{:s}{:05d}".format(ea_sign, int(math.fabs(1000.*ech_ang)))
        map_name = "slice_map_{:3s}_eo{:d}_ea{:s}".format(opticon[0:3], ech_order, ea_tag)
        slice_map = mosaic.copy(clear_data=True, copy_name=map_name)
        for hdu in slice_map.hdu_list:
            det_no = int(hdu.header['ID'])
            det_no_idxs = slice_coords['det_nos'] == det_no
            uni_slice_nos = np.unique(slice_coords['slice_nos'][det_no_idxs])
            for slice_no in uni_slice_nos:
                idxs = np.argwhere(slice_coords['slice_nos'] == slice_no)
                row_mins = np.array(slice_coords['row_mins'])[idxs]
                if len(row_mins) < 1:       # Catch cases where the slice is not on the detector
                    continue
                row_maxs = np.array(slice_coords['row_maxs'])[idxs][:,0]
                col_mins = np.array(slice_coords['col_mins'])[idxs][:,0]
                col_maxs = np.array(slice_coords['col_maxs'])[idxs][:,0]
                cols = 0.5 * (col_mins + col_maxs)
                row_min_fit = np.polyfit(cols, row_mins, 2)
                row_max_fit = np.polyfit(cols, row_maxs, 2)

                nr, nc = hdu.data.shape
                cs = np.arange(0, nc, 1)
                r1s = np.rint(np.polyval(row_min_fit, cs))
                r2s = np.rint(np.polyval(row_max_fit, cs))
                for c, r1, r2 in zip(cs, r1s, r2s):
                    hdu.data[int(r1):int(r2), int(c)] = int(slice_no)
        return slice_map

    @staticmethod
    def _calculate_fov(slice_map):
        """Estimate and print the illuminated field of view from the slice map.

        The number of non-zero slice-map pixels ``n_illum`` over all four
        detectors is converted to an along-slice extent::

            n_alphas  = n_illum / n_slices / n_cols / n_spifus / 2
            alpha_fov = n_alphas * Globals.alpha_pix        (8.7 mas per pixel)
            beta_fov  = Globals.beta_slice * n_slices       (20.7 mas per slice)

        with ``n_slices, n_spifus`` = (28, 1) in nominal and (3, 6) in extended
        mode and ``n_cols`` = ``Globals.det_format[1]`` = 2048.  The factor 2
        accounts for each slice appearing on two detectors along the dispersion
        direction.

        Parameters
        ----------
        slice_map : Mosaic
            Slice map; primary keyword 'HIERARCH AIT OPTICON' selects the mode.

        Returns
        -------
        None
            Prints 'Field of view = alpha x beta' (astropy Quantities in mas).

        Notes
        -----
        - Inconsistency: ``Globals.alpha_pix`` = 8.7 mas versus 8.2 mas in the
          irdb METIS_LMS package.
        - Inconsistency: the extended-mode ``n_slices`` = 3 assumes the 11..13
          slice set of ``_find_slices``.
        - Clean-up: return the values; the METIS-3667 comparison (> 0.500
          arcsec2, aspect ratio between 1:1 and 2:1) is only made in the legacy
          ``flood_stats``.
        """
        opticon = slice_map.primary_hdr['HIERARCH AIT OPTICON']
        n_rows, n_cols = Globals.det_format
        n_illum = 0
        for hdu in slice_map.hdu_list:
            n_illum += np.count_nonzero(hdu.data)

        n_slices = 28 if opticon == Globals.nominal else 3
        n_spifus = 1 if opticon == Globals.nominal else 6
        beta_fov = Globals.beta_slice * n_slices
        n_alphas = n_illum / n_slices / n_cols / n_spifus / 2
        alpha_fov = n_alphas * Globals.alpha_pix
        print("Field of view = {:9.2f} x {:9.2f}".format(alpha_fov, beta_fov))
        return

    @staticmethod
    def flood_stats(mosaic):
        """Legacy field-of-view estimate and slice map from a single flood mosaic tuple.

        Superseded by ``_find_slices`` / ``_make_slice_map`` / ``_calculate_fov``
        but retained because it prints the METIS-3667 requirement check.  For each
        detector and each profile column in ``profile_cols`` ({1: [600, 800, 1000,
        1200], 3: [600, 700, 800, 1200], 2 and 4: [1000, 1800, 1900, 2000]}) a
        5-column mean profile is thresholded at 1 % of its maximum; each on/off
        crossing pair is one slice whose along-slice length
        ``(row_off - r_on) * Globals.alpha_pix`` is accumulated.  Edge fits
        (degree 2, or ``n_profiles - 1`` if fewer than four columns) paint the
        slice map.  The total FOV is ``0.5 * ((alpha_1 + alpha_3) + (alpha_2 +
        alpha_4)) * Globals.beta_slice`` and the aspect ratio
        ``(alpha_ave / n_slices) / (beta_slice * n_slices)``.

        Parameters
        ----------
        mosaic : tuple
            Legacy ``(file_name, primary_hdr, hdus)``; 'HIERARCH ESO INS MODE' is
            read from the primary header, 'ID' from each HDU.  The mode is
            actually decided by the presence of '_nom_' in ``file_name``.

        Returns
        -------
        tuple
            ``(slice_map, profiles)`` where ``slice_map`` is a legacy mosaic tuple
            from ``OptTools.copy_mosaic`` and ``profiles`` is a list of
            ``(title, x_indices, y_signal, [on_points, off_points])``.

        Notes
        -----
        - Inconsistency: incompatible with ``lms_mosaic.Mosaic`` (tuple
          unpacking) and with ``Plot.profiles``, which expects ``(label, colour,
          det_no, profile_column, vals, pts)`` tuples.
        - Bug: in extended mode ``spifu_no`` starts at 0 and is only incremented
          when already non-zero, so it stays 0 and all pupil slices are painted
          with the same numbers.
        - Inconsistency: the printed text describes 10th / 90th percentile
          dark / bright levels, but ``dark_level`` and ``bright_level`` are never
          computed (printed as 0.0) and the cut is 1 % of the profile maximum.
        - Clean-up: ``u.arcsec2 = u.arcsec * u.arcsec`` monkey-patches the
          astropy units module; ``y_noise`` and ``illum_rows_sum`` are computed
          but unused.
        - The only caller is the non-functional ``Opt03.psf`` (as
          ``OptTools.flood_stats``, which does not exist).
        """
        file_name, hdr, hdus = mosaic
        opticon = hdr['HIERARCH ESO INS MODE']

        # Set up slice map object to hold slice images
        slice_map = OptTools.copy_mosaic(mosaic, clear_data=True, copy_name='slice_map')

        u.arcsec2 = u.arcsec * u.arcsec

        dark_pctile = 10.
        bright_pctile = 90.         # Choose the bright pixel limit to avoid hot pixels.
        alpha_cut = 0.5
        print()
        print("File = {:s}".format(file_name))
        fmt = "Dark pixels are defined as those < {:.0f}th percentile signal level"
        print(fmt.format(dark_pctile))
        fmt = "Illuminated pixels defined as those brighter than the {:.0f}th percentile signal level"
        print(fmt.format(bright_pctile))
        fmt = "alpha extent of each slice defined as distance between {:3.2f} of bright level"
        print(fmt.format(alpha_cut))
        fmt = "Illuminated pixel x slice fov = {} x {} mas"
        print(fmt.format(Globals.alpha_pix, Globals.beta_slice))
        profile_cols = {1: [600, 800, 1000, 1200], 3: [600, 700, 800, 1200],
                        2: [1000, 1800, 1900, 2000], 4: [1000, 1800, 1900, 2000]}

        print()
        fmt = "{:>10s},{:>10s},{:>10s},{:>10s}"
        print(fmt.format('Detector', 'dark',  'bright',    'illum.'))
        print(fmt.format('        ', 'level', 'level',        'fov'))
        print(fmt.format('        ', 'DN',       'DN',  '[sq_asec]'))
        fmt = "{:>10d},{:>10.2e},{:>10.2e},{:>10.3f}"

        # Separate slices by finding cuts in d_signal / d_row
        n_slices = 28 if '_nom_' in file_name else 3
        n_spifus = 0 if '_nom_' in file_name else 6

        profiles = []
        alpha_det = [0.]*4
        for hdu in hdus:
            det_no = int(hdu.header['ID'])
            img = np.array(hdu.data)            # Copy the image data
            det_idx = det_no - 1
            slice_coords = {'det_no': det_no, 'slice_nos': [], 'cols': [], 'row_mins': [], 'row_maxs': []}

            slice_no = 1

            n_profiles = len(profile_cols[det_no])
            dark_level, bright_level = 0., 0.           # Average signal cut levels for this detector
            for pr_col in profile_cols[det_no]:
                pr_col_hw = 2                           # Co-add 2 x pr_col_hw + 1 centred on pr_col.
                col1, col2 = pr_col - pr_col_hw, pr_col + pr_col_hw
                y_signal = np.nanmean(img[:, col1:col2+1], axis=1)
                y_noise = np.nanstd(img[:, col1:col2+1], axis=1)

                # Find the rows bounding the top 10 %ile, then replace them with the bottom 5 %ile value.
                cut_level = 0.01 * np.amax(y_signal)
                row_off = 0
                spifu_no = 0
                slice_count = 0
                on_rows = []
                off_rows = []
                while True:
                    # Find next bright pixel
                    on_indices = np.argwhere(y_signal[row_off:] > cut_level)
                    if len(on_indices) < 1:       # No more bright pixels found.
                        break
                    row_on = row_off + on_indices[0][0]
                    r_on = np.interp(cut_level, [y_signal[row_on-1], y_signal[row_on]], [row_on-1, row_on])
                    off_indices = np.argwhere(y_signal[row_on:] < cut_level)
                    row_off = row_on + off_indices[0][0]
                    slice_coords['cols'].append(pr_col)
                    slice_coords['row_mins'].append(row_on)
                    slice_coords['row_maxs'].append(row_off)
                    slice_coords['slice_nos'].append(slice_no)
                    r_off = np.interp(cut_level, [y_signal[row_off], y_signal[row_off-1]], [row_off, row_off-1])

                    alpha_slice = (row_off - r_on) * Globals.alpha_pix
                    alpha_det[det_idx] += alpha_slice
                    on_rows.append(r_on)
                    off_rows.append(r_off)

                    if n_spifus == 0:
                        slice_no += 1
                    else:                       # MSA set to 'extended'
                        slice_count += 1
                        slice_no += 1
                        if slice_count % n_slices == 0:
                            slice_no -= n_slices
                            if spifu_no != 0:
                                spifu_no += 1
                x_indices = np.arange(0, len(y_signal))
                title = "det {:d}, cols {:d}-{:d}".format(det_no, col1, col2)
                on_points = on_rows, [cut_level] * len(on_rows), 'green'
                off_points = off_rows, [cut_level] * len(off_rows), 'blue'
                profile = title, x_indices, y_signal, [on_points, off_points]
                profiles.append(profile)
                # Calculate total length of illuminated slices.
                illum_rows_sum = 0.
                for row_on, row_off in zip(on_rows, off_rows):
                    illum_rows = row_off - row_on
                    illum_rows_sum += illum_rows

            # Create the slice map (and calculate the intra-slice gap) from the table of slice bounds.
            poly_degree = 2 if n_profiles > 3 else n_profiles - 1

            slice_nos = np.array(slice_coords['slice_nos'], dtype='int64')
            unique_slice_nos = np.unique(slice_nos)

            slice_map_name, slice_map_hdr, slice_map_hdus = slice_map
            slice_map_hdu = slice_map_hdus[det_idx]
            for slice_no in unique_slice_nos:
                idx = np.where(slice_no == slice_nos)[0]
                cols = np.array(slice_coords['cols'])[idx]
                row_mins = np.array(slice_coords['row_mins'])[idx]
                row_maxs = np.array(slice_coords['row_maxs'])[idx]
                row_min_fit = np.polyfit(cols, row_mins, poly_degree)
                row_max_fit = np.polyfit(cols, row_maxs, poly_degree)
                nr, nc = slice_map_hdus[det_idx].data.shape
                cs = np.arange(0, nc, 1)
                r1s = np.rint(np.polyval(row_min_fit, cs))
                r2s = np.rint(np.polyval(row_max_fit, cs))
                for c, r1, r2 in zip(cs, r1s, r2s):
                    slice_map_hdu.data[int(r1):int(r2), int(c)] = slice_no + 100 * spifu_no
            alpha_det[det_idx] /= n_profiles
            det_fov = alpha_det[det_idx] * Globals.beta_slice
            fmt = "{:>10d},{:>10.1f},{:>10.1f},{:>10.3f}"
            print(fmt.format(det_no, dark_level, bright_level, det_fov.to(u.arcsec2)))

        alpha_02 = alpha_det[0] + alpha_det[2]
        alpha_13 = alpha_det[1] + alpha_det[3]
        alpha_ave = 0.5 * (alpha_02 + alpha_13)
        fov = alpha_ave * Globals.beta_slice
        print()
        print("Total field of view = {:5.3f} (cf METIS-3667, shall be > 0.500 arcsec2)".format(fov.to(u.arcsec2)))
        alpha_ext, beta_ext = alpha_ave / n_slices, Globals.beta_slice * n_slices
        aspect_ratio = alpha_ext / beta_ext
        print("Aspect ratio (alpha/beta) = {:5.3f}:1 (cf METIS-3667, shall be 1:1 < ar < 2:1)".format(aspect_ratio))
        return slice_map, profiles

    @staticmethod
    def print_inter_slice(slice_map):
        """Legacy brute-force inter-slice gap table from a slice map tuple.

        For each detector the slice numbers present along column 1024 are found;
        for each consecutive pair (``slice_no - 1``, ``slice_no``) and every
        column the gap is the first row of the upper slice minus the last row of
        the lower slice, and the minimum over columns is printed.

        Parameters
        ----------
        slice_map : tuple
            Legacy ``(name, primary_hdr, hdu_list)`` slice map.

        Returns
        -------
        None
            Printed table only.

        Notes
        -----
        - Inconsistency: tuple layout; incompatible with ``Mosaic`` slice maps
          from ``_make_slice_map``.  Not called anywhere in the package.
        - Bug: assumes both slices of a pair are present in every column;
          ``np.argwhere(...)[-1]`` raises IndexError otherwise.  Also assumes
          consecutive slice numbers, which fails across pupil-slice groups.
        - Clean-up: 2048 x n_slices full-column scans; the trailing print
          'Inter slice gap calculation' is misplaced.
        """
        _, _, hdu_list = slice_map
        fmt = "{:>12s},{:>12s},{:>12s},{:>12s},"
        print(fmt.format('Detector', 'Slice No.', 'Slice No.', 'Minimum'))
        print(fmt.format('No.', 'A', 'B', 'Gap'))
        fmt = "{:>12d},{:>12d},{:>12d},{:>12d},"
        for hdu in hdu_list:
            header, img = hdu.header, hdu.data
            det_no = int(header['ID'])
            # Sufficient to find slice numbers by searching along the central column (1024)
            values = np.unique(img[:, 1024])
            slice_nos = values[values > 0]
            for slice_no in slice_nos[1:]:
                gap_list = []
                for c in range(0, 2048):
                    cut = img[:, c]
                    row_a_top = np.argwhere(cut == slice_no - 1)[-1]
                    row_b_bot = np.argwhere(cut == slice_no)[0]      # Get indices of non-slice pixels.
                    gap_list.append(row_b_bot - row_a_top)
                gaps = np.array(gap_list)
                print(fmt.format(det_no, int(slice_no - 1), int(slice_no), gaps.min()))

        print("Inter slice gap calculation")
        return



    @staticmethod
    def _parse_abo(file_name):
        """Parse alpha, beta and observation number from a legacy '_grid' file name.

        Searches for '_grid' and then the tags '_a', '_b' and '_o'; the first two
        are signed ('p' / 'n' followed by three digits), the last unsigned.

        Parameters
        ----------
        file_name : str
            File name such as '..._grid_ap100_bn050_o001.fits'.

        Returns
        -------
        tuple of float
            ``(alpha, beta, obs_no)``.

        Notes
        -----
        - Inconsistency: current file names from ``lms_obs_map`` use
          'bb_iso_alpha_a{p|n}NNN_b{p|n}NNN' with no '_grid' or '_o' tags, so
          ``str.find`` returns -1 and the parse is meaningless for them.
        - Clean-up: duplicated verbatim in ``lmsaiv_opt03.Opt03._parse_abo``;
          neither copy is called.
        """
        signed = {'_a': True, '_b': True, '_o': False}
        ip = file_name.find('_grid') + 5        # Get start position of wavelength, alpha and beta sub strings
        abo = []
        for tag in signed:
            ip = file_name.find(tag, ip) + len(tag)
            sign = 1.0
            if signed[tag]:
                sign = 1. if file_name[ip] == 'p' else -1.
                ip += 1
            mag = float(file_name[ip: ip + 3])
            val = sign * mag
            abo.append(val)
        return tuple(abo)

